/**
 Example: Data Types
 */


#include <stdio.h>


int main(int argc, char **argv)
{
    // Declare variables
    int myNum = 5;
    float myFloatNum = 5.99;
    char myLetter = 'D';

    // Print variables
    printf("%d\n", myNum);
    printf("%f\n", myFloatNum);
    printf("%c\n", myLetter);

    return 0;
}
