#include <stdio.h>

int main()
{
    // Calculate the Area of a Rectangle

    // Create variables
    int length = 4;
    int width = 6;
    int area;

    // Calculate the area
    area = length * width;

    // Print the calculation
    printf("Length is:\t\t\t%d\n", length);
    printf("Width is:\t\t\t%d\n", width);
    printf("Area of the rectangle is\t%d\n", area);

    return 0;
}
