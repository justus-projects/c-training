#include <stdio.h>

int main()
{
    // Create variables
    int myNum = 15;             // Integer (whole number)
    float myFloatNum = 1.534;   // Floating point number (real number)
    char myLetter = 'J';        // Character

    // Print Variables
    printf("%d\n", myNum);
    printf("%f\n", myFloatNum);
    printf("%c\n", myLetter);

    return 0;
}
